async function uploadAndReleaseDeliverables(supabase, job, files, manifest, qa) {
  const request = job.response_engine_requests || {};
  const title = request.package_title || `${RESPONSE_ENGINE_LABEL} Candidate Submission Package`;
  const summary = String(manifest.summary || qa.summary || `${RESPONSE_ENGINE_LABEL} package completed.`).slice(0, 1000);
  const releaseNote = String(qa.summary || manifest.summary || "Automated quality checks completed.").slice(0, 1000);

  const { data: deliverable, error: deliverableError } = await supabase
    .from("deliverables")
    .insert({
      request_id: job.request_id,
      organization_id: job.organization_id,
      project_id: job.project_id,
      title,
      deliverable_type: `${RESPONSE_ENGINE_LABEL} package`,
      summary,
      status: "draft",
      created_by: null,
      uploaded_by: null,
    })
    .select("id")
    .single();
  if (deliverableError) throw deliverableError;

  const versionNumber = 1;
  const { data: version, error: versionError } = await supabase
    .from("deliverable_versions")
    .insert({
      deliverable_id: deliverable.id,
      request_id: job.request_id,
      organization_id: job.organization_id,
      project_id: job.project_id,
      version_number: versionNumber,
      status: "draft",
      summary,
      release_note: releaseNote,
      released_by: null,
      created_by: null,
    })
    .select("id")
    .single();
  if (versionError) throw versionError;

  const storagePrefix = `clients/${job.organization_id}/deliverables/${deliverable.id}/v${versionNumber}/`;
  const fileRecords = [];
  for (const [index, file] of files.entries()) {
    const buffer = await fsp.readFile(file.absolutePath);
    const storagePath = `${storagePrefix}${String(index + 1).padStart(2, "0")}-${safeFileName(file.fileName)}`;
    const contentType = OUTPUT_CONTENT_TYPES[file.extension] || "application/octet-stream";
    const { error: uploadError } = await supabase.storage
      .from("private-deliverables")
      .upload(storagePath, buffer, { contentType, upsert: false });
    if (uploadError) throw uploadError;
    fileRecords.push({
      storageBucket: "private-deliverables",
      storagePath,
      fileName: file.fileName,
      contentType,
      fileSizeBytes: buffer.length,
    });
  }

  const { data: releaseResult, error: releaseError } = await supabase
    .rpc("finalize_deliverable_release_v3", {
      p_organization_id: job.organization_id,
      p_project_id: job.project_id,
      p_request_id: job.request_id,
      p_deliverable_id: deliverable.id,
      p_version_id: version.id,
      p_version_number: versionNumber,
      p_title: title,
      p_release_note: releaseNote,
      p_credits_used: 0,
      p_files: fileRecords,
      p_actor_id: null,
    })
    .maybeSingle();
  if (releaseError) throw releaseError;
  if (!releaseResult) {
    const { data: releasedVersion, error: releasedVersionError } = await supabase
      .from("deliverable_versions")
      .select("id,status")
      .eq("id", version.id)
      .eq("deliverable_id", deliverable.id)
      .eq("organization_id", job.organization_id)
      .maybeSingle();
    if (releasedVersionError) throw releasedVersionError;

    const { data: releasedFiles, error: releasedFilesError } = await supabase
      .from("deliverable_version_files")
      .select("id")
      .eq("deliverable_version_id", version.id)
      .eq("deliverable_id", deliverable.id)
      .eq("organization_id", job.organization_id);
    if (releasedFilesError) throw releasedFilesError;

    const releasedFileCount = Array.isArray(releasedFiles) ? releasedFiles.length : 0;
    if (releasedVersion?.status !== "released" || releasedFileCount < fileRecords.length) {
      throw new Error("Deliverable release could not be finalized.");
    }
  }

  return { deliverableId: deliverable.id, versionId: version.id, versionNumber, files: fileRecords };
}

