function textQualityFailures(text, label = "output") {
  const value = String(text || "");
  const lower = value.toLowerCase();
  const failures = [];
  for (const punctuation of FORBIDDEN_PUNCTUATION) {
    if (value.includes(punctuation.value)) failures.push(`${label} contains ${punctuation.label} punctuation.`);
  }
  for (const phrase of BANNED_AI_STYLE_PHRASES) {
    if (lower.includes(phrase)) failures.push(`${label} contains generic AI-style phrase: ${phrase}.`);
  }
  for (const phrase of INTERNAL_TRACE_PHRASES) {
    if (lower.includes(phrase)) failures.push(`${label} contains internal or AI trace phrase: ${phrase}.`);
  }
  for (const term of RESTRICTED_DELIVERABLE_TERMS) {
    const regex = new RegExp(term.pattern, "i");
    if (regex.test(value)) failures.push(`${label} contains restricted deliverable term: ${term.label}.`);
  }
  return failures;
}

function hasRequiredFitGapAssessment(text) {
  const normalized = String(text || "").toLowerCase().replace(/\s+/g, " ");
  const hasTitle = /\bfit[\s-]?gap\b/.test(normalized);
  const hasStrongMatches = /strong match|strong matches|where the resume is strong/.test(normalized);
  const hasVisibleGaps = /visible gap|visible gaps|known gap|known gaps/.test(normalized);
  const hasFollowUp = /follow[\s-]?up question|candidate question|recruiter follow[\s-]?up/.test(normalized);
  return hasTitle && hasStrongMatches && hasVisibleGaps && hasFollowUp;
}

async function extractReadableText(file) {
  if (["docx", "xlsx", "pptx"].includes(file.extension)) {
    const pythonBin = process.env.PYTHON_BIN || "python3";
    const script = [
      "import re, sys, zipfile",
      "path = sys.argv[1]",
      "parts = []",
      "with zipfile.ZipFile(path) as archive:",
      "    for name in archive.namelist():",
      "        if not name.endswith('.xml'):",
      "            continue",
      "        if not (name.startswith('word/') or name.startswith('xl/') or name.startswith('ppt/') or name.startswith('docProps/')):",
      "            continue",
      "        try:",
      "            text = archive.read(name).decode('utf-8', 'ignore')",
      "        except Exception:",
      "            continue",
      "        text = re.sub(r'<[^>]+>', ' ', text)",
      "        parts.append(text)",
      "print('\\n'.join(parts))",
    ].join("\n");
    const result = await runProcess(pythonBin, ["-c", script, file.absolutePath], {
      cwd: path.dirname(file.absolutePath),
      env: safeCodexEnv(path.dirname(file.absolutePath)),
      timeoutMs: 30 * 1000,
    });
    if (result.code !== 0) {
      throw new Error(`Could not inspect output text quality for ${file.fileName}.`);
    }
    return result.stdout || "";
  }
  if (file.extension === "pdf") {
    const pythonBin = process.env.PYTHON_BIN || "python3";
    const script = [
      "import sys",
      "path = sys.argv[1]",
      "try:",
      "    from pypdf import PdfReader",
      "except Exception:",
      "    try:",
      "        from PyPDF2 import PdfReader",
      "    except Exception:",
      "        raise SystemExit(3)",
      "reader = PdfReader(path)",
      "parts = []",
      "metadata = getattr(reader, 'metadata', None) or {}",
      "for key, value in dict(metadata).items():",
      "    parts.append(str(key))",
      "    parts.append(str(value))",
      "for page in reader.pages:",
      "    try:",
      "        parts.append(page.extract_text() or '')",
      "    except Exception:",
      "        continue",
      "print('\\n'.join(parts))",
    ].join("\n");
    const result = await runProcess(pythonBin, ["-c", script, file.absolutePath], {
      cwd: path.dirname(file.absolutePath),
      env: safeCodexEnv(path.dirname(file.absolutePath)),
      timeoutMs: 30 * 1000,
    });
    if (result.code === 0) return result.stdout || "";
  }
  const buffer = await fsp.readFile(file.absolutePath);
  return buffer.toString("utf8");
}

async function scrubOfficeMetadata(file) {
  const pythonBin = process.env.PYTHON_BIN || "python3";
  const script = [
    "import os, re, sys, tempfile, zipfile",
    "import xml.etree.ElementTree as ET",
    "path = sys.argv[1]",
    "author = sys.argv[2]",
    "patterns = [r'\\bAI\\b', r'\\bartificial intelligence\\b', r'\\bHermes\\b', r'\\bCodex\\b', r'\\bOpenAI\\b', r'\\bChatGPT\\b', r'\\bClaude\\b', r'\\bLLM\\b', r'\\blarge language model\\b', r'\\bGPT\\b', r'\\bAnthropic\\b', r'\\bGemini\\b', r'\\bLlama\\b', r'\\bMistral\\b', r'\\bDeepSeek\\b', r'\\bPerplexity\\b', r'\\bGrok\\b']",
    "def clean(value):",
    "    text = '' if value is None else str(value)",
    "    for pattern in patterns:",
    "        text = re.sub(pattern, author, text, flags=re.I)",
    "    return text",
    "namespaces = {",
    "  'cp': 'http://schemas.openxmlformats.org/package/2006/metadata/core-properties',",
    "  'dc': 'http://purl.org/dc/elements/1.1/',",
    "  'dcterms': 'http://purl.org/dc/terms/',",
    "  'ep': 'http://schemas.openxmlformats.org/officeDocument/2006/extended-properties'",
    "}",
    "for prefix, uri in namespaces.items():",
    "    ET.register_namespace(prefix, uri)",
    "def set_child_text(root, qname, value):",
    "    child = root.find(qname)",
    "    if child is None:",
    "        child = ET.SubElement(root, qname)",
    "    child.text = value",
    "def scrub_tree(root):",
    "    for node in root.iter():",
    "        if node.text:",
    "            node.text = clean(node.text)",
    "        if node.tail:",
    "            node.tail = clean(node.tail)",
    "def update_xml(name, data):",
    "    try:",
    "        root = ET.fromstring(data)",
    "    except Exception:",
    "        return data",
    "    scrub_tree(root)",
    "    if name == 'docProps/core.xml':",
    "        set_child_text(root, '{%s}creator' % namespaces['dc'], author)",
    "        set_child_text(root, '{%s}lastModifiedBy' % namespaces['cp'], author)",
    "    if name == 'docProps/app.xml':",
    "        for tag in ['Application', 'Company', 'Manager']:",
    "            set_child_text(root, '{%s}%s' % (namespaces['ep'], tag), author)",
    "    return ET.tostring(root, encoding='utf-8', xml_declaration=True)",
    "tmp_fd, tmp_path = tempfile.mkstemp(suffix='.ooxml')",
    "os.close(tmp_fd)",
    "try:",
    "    with zipfile.ZipFile(path, 'r') as zin, zipfile.ZipFile(tmp_path, 'w', zipfile.ZIP_DEFLATED) as zout:",
    "        for item in zin.infolist():",
    "            data = zin.read(item.filename)",
    "            if item.filename.startswith('docProps/') and item.filename.endswith('.xml'):",
    "                data = update_xml(item.filename, data)",
    "            zout.writestr(item, data)",
    "    os.replace(tmp_path, path)",
    "finally:",
    "    if os.path.exists(tmp_path):",
    "        os.remove(tmp_path)",
  ].join("\n");
  const result = await runProcess(pythonBin, ["-c", script, file.absolutePath, DELIVERABLE_METADATA_AUTHOR], {
    cwd: path.dirname(file.absolutePath),
    env: safeCodexEnv(path.dirname(file.absolutePath)),
    timeoutMs: 30 * 1000,
  });
  if (result.code !== 0) {
    throw new Error(`Could not scrub Office metadata for ${file.fileName}.`);
  }
}

async function scrubPdfMetadata(file) {
  const pythonBin = process.env.PYTHON_BIN || "python3";
  const script = [
    "import os, sys, tempfile",
    "path = sys.argv[1]",
    "author = sys.argv[2]",
    "try:",
    "    from pypdf import PdfReader, PdfWriter",
    "except Exception:",
    "    try:",
    "        from PyPDF2 import PdfReader, PdfWriter",
    "    except Exception:",
    "        raise SystemExit(3)",
    "reader = PdfReader(path)",
    "if getattr(reader, 'is_encrypted', False):",
    "    raise SystemExit(4)",
    "writer = PdfWriter()",
    "for page in reader.pages:",
    "    writer.add_page(page)",
    "writer.add_metadata({",
    "    '/Title': author,",
    "    '/Author': author,",
    "    '/Subject': '',",
    "    '/Creator': author,",
    "    '/Producer': author,",
    "    '/Keywords': ''",
    "})",
    "fd, tmp_path = tempfile.mkstemp(suffix='.pdf')",
    "os.close(fd)",
    "try:",
    "    with open(tmp_path, 'wb') as handle:",
    "        writer.write(handle)",
    "    os.replace(tmp_path, path)",
    "finally:",
    "    if os.path.exists(tmp_path):",
    "        os.remove(tmp_path)",
  ].join("\n");
  const result = await runProcess(pythonBin, ["-c", script, file.absolutePath, DELIVERABLE_METADATA_AUTHOR], {
    cwd: path.dirname(file.absolutePath),
    env: safeCodexEnv(path.dirname(file.absolutePath)),
    timeoutMs: 30 * 1000,
  });
  if (result.code === 3) {
    throw new Error(`PDF metadata scrubber is unavailable for ${file.fileName}. Install pypdf on the worker host or release a Word or Excel output instead.`);
  }
  if (result.code === 4) {
    throw new Error(`PDF metadata cannot be scrubbed because ${file.fileName} is encrypted.`);
  }
  if (result.code !== 0) {
    throw new Error(`Could not scrub PDF metadata for ${file.fileName}.`);
  }
}

async function scrubOutputMetadata(files) {
  for (const file of files) {
    if (["docx", "xlsx", "pptx"].includes(file.extension)) {
      await scrubOfficeMetadata(file);
    } else if (file.extension === "pdf") {
      await scrubPdfMetadata(file);
    }
  }
}

async function outputTextQualityFailures(files, options = {}) {
  const failures = [];
  const textBlocks = [];
  for (const file of files) {
    const text = await extractReadableText(file);
    textBlocks.push(text);
    failures.push(...textQualityFailures(text, file.fileName));
  }
  if (options.requireFitGapAssessment && !hasRequiredFitGapAssessment(textBlocks.join("\n"))) {
    failures.push("Client deliverables are missing the required Fit-Gap Assessment section with strong matches, visible gaps, and candidate follow-up questions.");
  }
  return [...new Set(failures)];
}

