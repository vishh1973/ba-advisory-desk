async function claimNextJob(supabase, requestId = "") {
  const selectColumns = "id,request_id,organization_id,project_id,status,provider,provider_mode,attempts,max_attempts,qa_score,qa_report,output_manifest,error_message,queued_at";
  let query = supabase
    .from("response_engine_jobs")
    .select(selectColumns)
    .eq("status", "queued")
    .order("queued_at", { ascending: true })
    .limit(5);
  if (requestId) query = query.eq("request_id", requestId);
  const { data, error } = await query;
  if (error) throw error;

  for (const job of data || []) {
    const { data: claimed, error: claimError } = await supabase
      .from("response_engine_jobs")
      .update({
        status: "processing",
        picked_up_at: new Date().toISOString(),
        attempts: Number(job.attempts || 0) + 1,
        error_message: null,
      })
      .eq("id", job.id)
      .eq("status", "queued")
      .select(selectColumns)
      .maybeSingle();
    if (claimError) throw claimError;
    if (claimed?.id) return hydrateJob(supabase, claimed);
  }
  return null;
}

async function hydrateJob(supabase, job) {
  const [
    { data: responseRequest, error: responseRequestError },
    { data: baseRequest, error: baseRequestError },
    { data: organization, error: organizationError },
  ] = await Promise.all([
    supabase
      .from("response_engine_requests")
      .select(
        "request_id,submitted_by,package_title,candidate_name,target_role,opportunity_name,automation_notes,output_options,output_formats,file_context,credit_cost,status"
      )
      .eq("request_id", job.request_id)
      .maybeSingle(),
    supabase
      .from("requests")
      .select("request_code,due_at,attachment_description")
      .eq("id", job.request_id)
      .maybeSingle(),
    supabase.from("client_organizations").select("name,billing_email").eq("id", job.organization_id).maybeSingle(),
  ]);

  if (responseRequestError) throw responseRequestError;
  if (baseRequestError) throw baseRequestError;
  if (organizationError) throw organizationError;
  if (!responseRequest?.request_id) throw new Error(`${RESPONSE_ENGINE_LABEL} request details were not found for the claimed job.`);
  let submitter = null;
  if (responseRequest.submitted_by) {
    const { data: submitterProfile, error: submitterError } = await supabase
      .from("profiles")
      .select("id,first_name,last_name,work_email")
      .eq("id", responseRequest.submitted_by)
      .maybeSingle();
    if (submitterError) throw submitterError;
    submitter = submitterProfile || null;
  }

  return {
    ...job,
    response_engine_requests: {
      ...responseRequest,
      requests: baseRequest || {},
    },
    client_organizations: organization || {},
    submitter_profile: submitter,
  };
}

async function readSourceFiles(supabase, job) {
  const { data, error } = await supabase
    .from("request_files")
    .select("id,storage_path,file_name,file_role,file_description,file_size_bytes,mime_type,created_at")
    .eq("request_id", job.request_id)
    .eq("organization_id", job.organization_id)
    .is("deleted_at", null)
    .order("created_at", { ascending: true });
  if (error) throw error;
  if (!data?.length) throw new Error(`No source files were found for the ${RESPONSE_ENGINE_LABEL} request.`);
  if (data.length > DEFAULT_MAX_RESPONSE_ENGINE_SOURCE_FILES) throw new Error(`${RESPONSE_ENGINE_LABEL} packages accept no more than ${DEFAULT_MAX_RESPONSE_ENGINE_SOURCE_FILES} source files after follow-up evidence is added.`);
  return data;
}

async function downloadSourceFiles(supabase, files, inputDir) {
  await fsp.mkdir(inputDir, { recursive: true });
  const downloaded = [];
  for (const [index, file] of files.entries()) {
    const ext = extensionOf(file.file_name);
    const localName = `${String(index + 1).padStart(2, "0")} - ${safeFileName(file.file_name || `source.${ext || "bin"}`)}`;
    const localPath = path.join(inputDir, localName);
    const { data, error } = await supabase.storage.from("client-files").download(file.storage_path);
    if (error || !data) throw new Error(`Could not download source file: ${file.file_name || file.id}`);
    const buffer = Buffer.from(await data.arrayBuffer());
    await fsp.writeFile(localPath, buffer);
    downloaded.push({
      ...file,
      localPath,
      localName,
      sizeBytes: buffer.length,
    });
  }
  return downloaded;
}

